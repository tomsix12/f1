# Builds the bundled 2026 F1 season snapshot used by the landing page.
# Sources: Jolpica F1 (race metadata) + OpenF1 (session start/end times, UTC).
$ErrorActionPreference = 'Stop'
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

$season = 2026
function Get-Json($url) {
  $client = New-Object System.Net.WebClient
  $client.Encoding = [Text.Encoding]::UTF8
  $client.Headers.Add('User-Agent', 'tomsix-web/1.0')
  return ($client.DownloadString($url) | ConvertFrom-Json)
}

$races    = (Get-Json "https://api.jolpi.ca/ergast/f1/$season/races.json").MRData.RaceTable.Races
$sessions = Get-Json "https://api.openf1.org/v1/sessions?year=$season"
$meetings = Get-Json "https://api.openf1.org/v1/meetings?year=$season"

$countryNames = @{ 'USA' = 'United States'; 'UK' = 'United Kingdom'; 'UAE' = 'United Arab Emirates' }
$iso2 = @{
  'Australia' = 'AU'; 'China' = 'CN'; 'Japan' = 'JP'; 'Bahrain' = 'BH'
  'Saudi Arabia' = 'SA'; 'United States' = 'US'; 'Canada' = 'CA'; 'Monaco' = 'MC'
  'Spain' = 'ES'; 'Austria' = 'AT'; 'United Kingdom' = 'GB'; 'Belgium' = 'BE'
  'Hungary' = 'HU'; 'Netherlands' = 'NL'; 'Italy' = 'IT'; 'Azerbaijan' = 'AZ'
  'Malaysia' = 'MY'; 'Singapore' = 'SG'; 'Mexico' = 'MX'; 'Brazil' = 'BR'
  'Qatar' = 'QA'; 'United Arab Emirates' = 'AE'
}

function To-UtcString($value) {
  ([datetimeoffset]::Parse($value, [Globalization.CultureInfo]::InvariantCulture)).UtcDateTime.ToString(
    'yyyy-MM-ddTHH:mm:ssZ', [Globalization.CultureInfo]::InvariantCulture)
}

$result = @()
foreach ($race in $races) {
  $raceSession = $sessions | Where-Object {
    $_.session_type -eq 'Race' -and $_.session_name -eq 'Race' -and
    (To-UtcString $_.date_start).Substring(0, 10) -eq $race.date
  } | Select-Object -First 1

  if (-not $raceSession) {
    Write-Warning "No OpenF1 meeting matched round $($race.round) ($($race.raceName))"
    continue
  }

  $meeting = $meetings | Where-Object { $_.meeting_key -eq $raceSession.meeting_key } | Select-Object -First 1
  $country = $race.Circuit.Location.country
  if ($countryNames.ContainsKey($country)) { $country = $countryNames[$country] }
  $sessionList = @()
  foreach ($s in ($sessions | Where-Object { $_.meeting_key -eq $meeting.meeting_key } | Sort-Object { [datetimeoffset]$_.date_start })) {
    $sessionList += [ordered]@{
      name  = $s.session_name
      type  = $s.session_type
      start = To-UtcString $s.date_start
      end   = To-UtcString $s.date_end
    }
  }

  $result += [ordered]@{
    round        = [int]$race.round
    name         = $race.raceName
    officialName = $meeting.meeting_official_name
    circuit      = $meeting.circuit_short_name
    locality     = $meeting.location
    country      = $country
    countryCode  = $iso2[$country]
    sprint       = [bool]($sessionList | Where-Object { $_.name -eq 'Sprint' })
    sessions     = $sessionList
  }
}

$payload = [ordered]@{
  season    = $season
  generated = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
  sources   = @(
    'https://api.openf1.org/v1/sessions',
    'https://api.jolpi.ca/ergast/f1'
  )
  meetings  = $result
}

$json = $payload | ConvertTo-Json -Depth 8
$root = Split-Path -Parent $PSScriptRoot
$js = "// Generated by tools/build-data.ps1 - do not edit by hand.`nwindow.F1_SEASON = $json;`n"
[IO.File]::WriteAllText((Join-Path $root 'js\data.js'), $js, (New-Object Text.UTF8Encoding($false)))
[IO.File]::WriteAllText((Join-Path $root 'data\season-2026.json'), $json, (New-Object Text.UTF8Encoding($false)))

Write-Host "Wrote $($result.Count) rounds / $(($result | ForEach-Object { $_.sessions.Count } | Measure-Object -Sum).Sum) sessions."